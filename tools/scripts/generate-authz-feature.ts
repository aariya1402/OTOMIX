// GAP-015, RBAC-M12: parse permissions catalog from SQL seeds, cross with ROUTE_SCOPES
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROUTE_SCOPES } from '../../packages/gateway/src/scopes.ts';

const SEED_DIR = resolve(__dirname, '..', '..', 'packages', 'db', 'seeds');

function parsePermissionKeys(sql: string): string[] {
  const keys: string[] = [];
  const re = /\(\s*'([^']+)'\s*,\s*'[^']*'\s*,\s*'[^']*'\s*,\s*(?:true|false)\s*,\s*(?:true|false)\s*\)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(sql)) !== null) { keys.push(m[1]); }
  return keys;
}

function loadCatalog(): Set<string> {
  const files = ['permissions.seed.sql', 'permissions.admin.seed.sql'];
  const all = new Set<string>();
  for (const f of files) {
    try {
      const sql = readFileSync(resolve(SEED_DIR, f), 'utf8');
      for (const k of parsePermissionKeys(sql)) all.add(k);
    } catch { /* file may not exist */ }
  }
  return all;
}

function concretePath(routePath: string): string {
  return routePath.replace(/\{[^}]+\}/g, 'abc123');
}

function main(): void {
  const catalog = loadCatalog();
  const lines: string[] = [];
  lines.push('# AUTO-GENERATED by tools/scripts/generate-authz-feature.ts');
  lines.push('# Source: permissions.seed.sql + permissions.admin.seed.sql (catalog)');
  lines.push('#       x ROUTE_SCOPES (packages/gateway/src/scopes.ts)');
  lines.push('# Permission keys in catalog: ' + catalog.size);
  lines.push('');
  lines.push('Feature: Authorization matrix (route x permissions)');
  lines.push('  OTOMIX §7.1 requires explicit permission mapping per endpoint.');
  lines.push('  GAP-015: permissions are dynamic (catalog in DB).');
  lines.push('');

  let total = 0;
  for (const route of ROUTE_SCOPES) {
    const cpath = concretePath(route.path);
    const routeScopes = route.scopes;

    // Positive: user has all required scopes
    lines.push('  @authz');
    lines.push('  # perm: ' + routeScopes.join(',') + ' (all required)');
    lines.push('  Scenario: ALLOW ' + route.method + ' ' + cpath + ' with all required perms');
    lines.push('    Given a user with permissions "' + routeScopes.join(',') + '"');
    lines.push('    When I send "' + route.method + '" to "' + cpath + '"');
    lines.push('    Then the response status should be 200');
    lines.push('');
    total++;

    // Negative: user has no perms
    lines.push('  @authz');
    lines.push('  # perm: (none)');
    lines.push('  Scenario: DENY ' + route.method + ' ' + cpath + ' with no perms');
    lines.push('    Given a user with no permissions');
    lines.push('    When I send "' + route.method + '" to "' + cpath + '"');
    lines.push('    Then the response status should be 403');
    lines.push('');
    total++;

    // Per-permission: user has only one required scope -> should still allow (OR semantics)
    if (routeScopes.length > 1) {
      for (const s of routeScopes) {
        lines.push('  @authz');
        lines.push('  # perm: ' + s + ' (one of required)');
        lines.push('  Scenario: ALLOW ' + route.method + ' ' + cpath + ' with only ' + s);
        lines.push('    Given a user with permissions "' + s + '"');
        lines.push('    When I send "' + route.method + '" to "' + cpath + '"');
        lines.push('    Then the response status should be 200');
        lines.push('');
        total++;
      }
    }
  }

  const out = resolve(__dirname, '..', '..', 'features', 'authz.feature');
  writeFileSync(out, lines.join('\n'), 'utf8');
  process.stdout.write('generated ' + out + '\nscenarios: ' + total + '\ncatalog keys: ' + catalog.size + '\nroutes: ' + ROUTE_SCOPES.length + '\n');
}

main();