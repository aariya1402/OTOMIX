// OTOMIX §7.1; §7.11; §10.4
// Generates features/authz.feature from ROUTE_SCOPES + the §7.11 role table.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROUTE_SCOPES } from '../../packages/gateway/src/scopes.ts';

interface RoleDef {
  name: string;
  scopes: string[];
}

// §7.11 OTOMIX issuable scopes per role (verbatim).
const ROLES: RoleDef[] = [
  { name: 'Audio DSP Admin', scopes: ['dsp:*', 'audio:tuning', 'mastering:*'] },
  { name: 'Content & Licensing Admin', scopes: ['catalog:*'] },
  { name: 'System Admin', scopes: ['sys:*', 'users:*', 'billing:*'] },
  { name: 'End User', scopes: ['user:read', 'local:process'] },
];

function concretePath(routePath: string): string {
  return routePath.replace(/\{[^}]+\}/g, 'abc123');
}

function escapeQuotes(s: string): string {
  return s.replace(/"/g, '\\"');
}

function main(): void {
  const lines: string[] = [];
  lines.push('# AUTO-GENERATED by tools/scripts/generate-authz-feature.ts');
  lines.push('# Source: ROUTE_SCOPES (packages/gateway/src/scopes.ts) + §7.11 role table');
  lines.push('# Do not edit by hand. Regenerate to pick up registry changes.');
  lines.push('');
  lines.push('Feature: Authorization matrix (role x endpoint)');
  lines.push('  OTOMIX §7.1 requires explicit token scope mapping per endpoint.');
  lines.push('  §7.11 defines the issuable scopes for each role under tenant otomix.');
  lines.push('');

  let totalScenarios = 0;
  let allowedCount = 0;
  let deniedCount = 0;

  for (const role of ROLES) {
    lines.push('  # §7.11 ' + role.name + ' -> ' + role.scopes.join(', '));
    for (const route of ROUTE_SCOPES) {
      const granted = route.scopes.some(function (s) { return role.scopes.indexOf(s) >= 0; });
      const expected = granted ? 200 : 403;
      const cpath = concretePath(route.path);
      lines.push('  @authz');
      lines.push('  Scenario: ' + role.name + ' -> ' + route.method + ' ' + cpath + ' (' + (granted ? 'allowed' : 'denied') + ')');
      lines.push('    Given a token for role "' + escapeQuotes(role.name) + '"');
      lines.push('    When I send "' + route.method + '" to "' + cpath + '"');
      lines.push('    Then the response status should be ' + expected);
      lines.push('');
      totalScenarios++;
      if (granted) allowedCount++; else deniedCount++;
    }
  }

  const outPath = resolve(__dirname, '..', '..', 'features', 'authz.feature');
  writeFileSync(outPath, lines.join('\n'), { encoding: 'utf8' });

  process.stdout.write(
    'generated ' + outPath + '\n' +
    'total scenarios: ' + totalScenarios + '\n' +
    'allowed (200): ' + allowedCount + '\n' +
    'denied (403): ' + deniedCount + '\n'
  );
}

main();